-- 7. RLS Policies for Public Form Submissions (INSERT) & Admin/DPO Management
DROP POLICY IF EXISTS "Public can insert contact_messages" ON public.contact_messages;
CREATE POLICY "Public can insert contact_messages"
  ON public.contact_messages
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    length(trim(coalesce(name, ''))) >= 2
    AND length(trim(coalesce(email, ''))) >= 5
    AND length(coalesce(message, '')) <= 10000
  );

