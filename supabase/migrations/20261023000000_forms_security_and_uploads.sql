-- 6. Server-side Anti-Spam, Honeypot & Rate Limit Trigger Function
CREATE OR REPLACE FUNCTION public.enforce_form_security_and_rate_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  recent_count INTEGER;
BEGIN
  -- Reject if honeypot trap was triggered
  IF NEW.security_meta IS NOT NULL AND COALESCE(NEW.security_meta->>'honeypot', '') <> '' THEN
    RAISE EXCEPTION 'Submissão bloqueada pelo filtro de segurança anti-spam.';
  END IF;

  -- Enforce rate limit per ip_hash (max 8 submissions per 10 minutes per table)
  IF NEW.ip_hash IS NOT NULL AND length(NEW.ip_hash) > 8 THEN
    EXECUTE format(
      'SELECT count(*) FROM public.%I WHERE ip_hash = $1 AND created_at > NOW() - INTERVAL ''10 minutes''',
      TG_TABLE_NAME
    ) INTO recent_count USING NEW.ip_hash;

    IF recent_count >= 8 THEN
      RAISE EXCEPTION 'Limite de envios excedido. Por favor, aguarde alguns minutos antes de tentar novamente.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.enforce_form_security_and_rate_limit() FROM anon, authenticated;

